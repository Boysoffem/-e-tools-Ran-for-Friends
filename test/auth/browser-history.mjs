import assert from "node:assert/strict";
import path from "node:path";
import {tmpdir} from "node:os";

export async function checkBrowsingHistory ({admin, visitor, visitorContext, base, login}) {
	const session = await visitor.request.get(`${base}/api/auth/session`).then(it => it.json());
	const key = `five:browsing-history:v1:${session.user.historyKey}`;
	const read = () => visitor.evaluate(key => JSON.parse(localStorage.getItem(key) || "{\"entries\":[]}"), key);
	const waitForVisit = url => visitor.waitForFunction(({key, url}) => {
		try { return JSON.parse(localStorage.getItem(key) || "{}").entries?.some(entry => entry.url === url); } catch { return false; }
	}, {key, url});
	const requests = [];
	const observe = request => requests.push({url: request.url(), body: request.postData(), headers: request.headers()});
	visitor.on("request", observe);
	await visitor.goto(`${base}/index.html?transient=value#private-history-entry`);
	await waitForVisit("/index.html#private-history-entry");
	await visitor.evaluate(() => { document.title = "Private history title <img src=x>"; });
	await visitor.waitForFunction(key => JSON.parse(localStorage.getItem(key)).entries[0].title === "Private history title <img src=x>", key);
	assert.ok(!(await read()).entries.some(entry => entry.url.includes("?")));
	await visitor.goto(`${base}/actions.html#attack_phb`);
	await visitor.waitForFunction(() => document.title.startsWith("Attack"));
	await waitForVisit("/actions.html#attack_phb");
	await visitor.waitForFunction(key => JSON.parse(localStorage.getItem(key)).entries.find(entry => entry.url === "/actions.html#attack_phb")?.title.startsWith("Attack"), key);
	await visitor.evaluate(() => { location.hash = "dash_phb"; });
	await waitForVisit("/actions.html#dash_phb");
	await visitor.evaluate(() => { location.hash = "attack_phb"; });
	await visitor.waitForFunction(key => JSON.parse(localStorage.getItem(key)).entries[0].url === "/actions.html#attack_phb", key);
	assert.equal((await read()).entries.filter(entry => entry.url === "/actions.html#attack_phb").length, 1);
	await visitor.goto(`${base}/login.html`);
	await visitor.locator("#history-list a").first().waitFor();
	assert.match(await visitor.locator("#history-list").innerText(), /Private history title <img src=x>/);
	assert.equal(await visitor.locator("#history-list img").count(), 0);
	assert.ok(!(await read()).entries.some(entry => /login|admin-accounts/.test(entry.url)));
	assert.ok(!requests.some(request => JSON.stringify(request).includes("private-history-entry") || JSON.stringify(request).includes("Private history title")));
	assert.ok(requests.filter(request => request.url.endsWith("/api/auth/session")).every(request => !request.body && !request.headers.referer));
	const accounts = await admin.request.get(`${base}/api/auth/accounts`).then(it => it.json());
	assert.ok(!JSON.stringify(accounts).includes("private-history-entry"));
	assert.ok(!JSON.stringify(accounts).includes("historyKey"));
	assert.equal((await admin.request.get(`${base}/api/auth/history`)).status(), 404);
	console.log("PASS: real pages and hash navigation appear locally with safe titles, no duplicates, and no history sent to the server or admin list");
	await visitor.locator("#history-pause").click();
	await visitor.waitForFunction(() => document.querySelector("#history-pause").textContent === "Resume history");
	const paused = await read();
	await visitor.goto(`${base}/index.html#paused-visit`);
	await visitor.locator("[data-account-nav] a").filter({hasText: "My account"}).waitFor();
	await visitor.waitForTimeout(700);
	assert.deepEqual(await read(), paused);
	await visitor.goto(`${base}/login.html`);
	await visitor.locator("#history-pause").filter({hasText: "Resume history"}).click();
	await visitor.waitForFunction(() => document.querySelector("#history-pause").textContent === "Pause history");
	await visitor.goto(`${base}/index.html#resumed-visit`);
	await waitForVisit("/index.html#resumed-visit");
	await visitor.goto(`${base}/login.html`);
	await visitor.locator("#history-list li").filter({has: visitor.locator("a[href=\"/index.html#resumed-visit\"]")}).getByRole("button").click();
	await visitor.waitForFunction(key => !JSON.parse(localStorage.getItem(key)).entries.some(entry => entry.url === "/index.html#resumed-visit"), key);
	console.log("PASS: pause persists between pages, resume records again, and individual entries can be removed");
	await visitor.setViewportSize({width: 390, height: 844});
	assert.equal(await visitor.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
	await visitor.screenshot({path: path.join(tmpdir(), "five-history-mobile.png"), fullPage: true});
	await visitor.setViewportSize({width: 1280, height: 900});
	await visitor.screenshot({path: path.join(tmpdir(), "five-history.png"), fullPage: true});
	const otherTab = await visitorContext.newPage();
	await otherTab.goto(`${base}/index.html#other-tab`);
	await otherTab.waitForFunction(key => JSON.parse(localStorage.getItem(key)).entries.some(entry => entry.url === "/index.html#other-tab"), key);
	const beforeLogout = await read();
	await visitor.locator("#signout").click();
	await visitor.locator("#signed-out").waitFor({state: "visible"});
	assert.equal(await visitor.locator("#history-list li").count(), 0);
	await otherTab.evaluate(() => { location.hash = "signed-out-visit"; });
	await otherTab.waitForTimeout(700);
	assert.deepEqual(await read(), beforeLogout);
	await login(visitor, "google", {email: "admin@example.com", name: "Site Owner", subject: "owner-id"});
	await visitor.locator("#browsing-history").waitFor({state: "visible"});
	assert.equal(await visitor.locator("#history-list li").count(), 0);
	const ownerKey = (await visitor.request.get(`${base}/api/auth/session`).then(it => it.json())).user.historyKey;
	await otherTab.evaluate(() => { location.hash = "wrong-account-visit"; });
	await otherTab.waitForTimeout(700);
	assert.deepEqual(await read(), beforeLogout);
	assert.equal(await visitor.evaluate(key => localStorage.getItem(`five:browsing-history:v1:${key}`), ownerKey), null);
	await visitor.locator("#signout").click();
	await visitor.locator("#signed-out").waitFor({state: "visible"});
	await login(visitor, "github", {email: "friend@example.com", name: "Friend", subject: "9876"});
	await visitor.locator("#history-list a").first().waitFor();
	assert.deepEqual(await read(), beforeLogout);
	await otherTab.goto(`${base}/login.html`);
	await otherTab.locator("#history-list a").first().waitFor();
	await visitor.locator("#signout").click();
	await visitor.locator("#signed-out").waitFor({state: "visible"});
	await otherTab.locator("#signed-out").waitFor({state: "visible"});
	assert.equal(await otherTab.locator("#history-list li").count(), 0);
	await otherTab.close();
	await login(visitor, "github", {email: "friend@example.com", name: "Friend", subject: "9876"});
	await visitor.locator("#history-list a").first().waitFor();
	console.log("PASS: logout clears the visible history across tabs; account switches stay separate; the same identity recovers its local list");
	visitor.once("dialog", dialog => dialog.accept());
	await visitor.locator("#history-clear").click();
	await visitor.waitForFunction(() => document.querySelector("#history-list").children.length === 0 && document.querySelector("#history-clear").disabled);
	assert.deepEqual((await read()).entries, []);
	// Reject tampered links and recover from damaged browser data without executing HTML.
	await visitor.evaluate(key => localStorage.setItem(key, JSON.stringify({entries: [
		{url: "javascript:alert(1)", title: "bad script", visitedAt: Date.now()},
		{url: "https://attacker.example/index.html", title: "external", visitedAt: Date.now()},
		{url: "/auth/google/callback?code=private", title: "callback", visitedAt: Date.now()},
		...Array.from({length: 110}, (_, index) => ({url: `/index.html#entry-${index}`, title: "<svg onload=alert(1)>", visitedAt: Date.now() - index})),
	]})), key);
	await visitor.reload();
	await visitor.waitForFunction(() => document.querySelectorAll("#history-list li").length === 100);
	assert.equal(await visitor.locator("#history-list svg").count(), 0);
	assert.ok((await visitor.locator("#history-list a").evaluateAll(links => links.map(link => link.getAttribute("href")))).every(url => url.startsWith("/index.html#entry-")));
	await visitor.evaluate(key => localStorage.setItem(key, "damaged data"), key);
	await visitor.reload();
	await visitor.waitForFunction(() => document.querySelector("#history-status").textContent.startsWith("No history yet"));
	await visitor.goto(`${base}/index.html#recovered-visit`);
	await waitForVisit("/index.html#recovered-visit");
	const beforeFailure = await read();
	// A session lookup failure must not save the visit under a cached identity.
	await visitor.route(`${base}/api/auth/session`, route => route.fulfill({status: 503, contentType: "application/json", body: "{}"}));
	await visitor.evaluate(() => { location.hash = "failed-session-visit"; });
	await visitor.waitForTimeout(700);
	assert.deepEqual(await read(), beforeFailure);
	await visitor.unroute(`${base}/api/auth/session`);
	await visitor.route(`${base}/api/auth/session`, route => route.fulfill({contentType: "application/json", body: JSON.stringify({...session, user: null})}));
	await visitor.evaluate(() => { location.hash = "expired-session-visit"; });
	await visitor.waitForTimeout(700);
	assert.deepEqual(await read(), beforeFailure);
	await visitor.unroute(`${base}/api/auth/session`);
	// Background tabs start saving only when the person actually views them.
	const background = await visitorContext.newPage();
	await background.addInitScript(() => Object.defineProperty(document, "visibilityState", {get: () => window.historyTestVisible ? "visible" : "hidden"}));
	await background.goto(`${base}/index.html#background-visit`);
	await background.locator("[data-account-nav] a").filter({hasText: "My account"}).waitFor();
	assert.ok(!(await read()).entries.some(entry => entry.url === "/index.html#background-visit"));
	await background.evaluate(() => { window.historyTestVisible = true; document.dispatchEvent(new Event("visibilitychange")); });
	await waitForVisit("/index.html#background-visit");
	await background.close();
	const separateBrowser = await visitorContext.browser().newContext();
	const separatePage = await separateBrowser.newPage();
	await login(separatePage, "github", {email: "friend@example.com", name: "Friend", subject: "9876"});
	await separatePage.locator("#browsing-history").waitFor({state: "visible"});
	assert.equal(await separatePage.locator("#history-list li").count(), 0);
	await separateBrowser.close();
	const blocked = await visitorContext.newPage();
	await blocked.addInitScript(() => Object.defineProperty(window, "localStorage", {get () { throw new DOMException("Blocked", "SecurityError"); }}));
	await blocked.goto(`${base}/login.html`);
	await blocked.waitForFunction(() => document.querySelector("#history-status").textContent.includes("blocking local storage"));
	assert.equal(await blocked.locator("#signed-in").isVisible(), true);
	assert.equal(await blocked.locator("#history-pause").isDisabled(), true);
	await blocked.close();
	visitor.off("request", observe);
	await visitor.goto(`${base}/login.html`);
	console.log("PASS: clearing, limits, unsafe links, damaged/blocked storage, expired/unavailable sessions, background tabs, and browser isolation are handled safely");
}
