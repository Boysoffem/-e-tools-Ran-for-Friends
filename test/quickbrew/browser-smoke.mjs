import {chromium} from "playwright";
import {spawn} from "node:child_process";
import assert from "node:assert/strict";
import {mkdtemp, rm, readFile} from "node:fs/promises";
import {tmpdir} from "node:os";
import path from "node:path";
const temp = await mkdtemp(path.join(tmpdir(), "homebrew-qa-"));
const baseUrl = "http://127.0.0.1:3140";
const server = spawn(process.execPath, ["server.js"], {env: {...process.env, PORT: "3140", HOMEBREW_STORAGE_DIR: path.join(temp, "shared"), DISABLE_AUTO_UPDATE: "1"}, stdio: "pipe"});
for (let i = 0; i < 100; i++) { if (server.exitCode != null) throw new Error("Test server exited"); try { if ((await fetch(`${baseUrl}/api/shared-homebrew`)).ok) break; } catch { /* Retry while the isolated test server starts. */ } await new Promise(resolve => setTimeout(resolve, 100)); }
const browser = await chromium.launch({headless: true});
try {
	const context = await browser.newContext();
	const page = await context.newPage();
	page.setDefaultTimeout(30000);
	const errors = [];
	page.on("pageerror", e => { errors.push(e.message); console.log("PAGEERROR", e.message); });
	await page.goto(`${baseUrl}/managebrew.html`);
	await page.waitForSelector("[name=parentClass] option:nth-child(2)", {timeout: 60000, state: "attached"});
	const form = page.locator("[data-editor]");
	await form.locator("[name=name]").fill("QA Star Blade");
	await form.locator("[name=kind]").selectOption("weapon");
	await form.locator("[name=description]").fill("This blade glows softly.");
	await page.getByRole("button", {name: "Check & preview", exact: true}).click();
	await page.waitForFunction(() => document.querySelector("[data-validation]").textContent.includes("Format and links checked."));
	await page.locator("[data-save]").click();
	await page.waitForFunction(() => document.querySelector("[data-status]").textContent.includes("Shared 1 records"));
	console.log("weapon save PASS");
	const saved = await page.evaluate(async () => BrewUtil2._sharedClient.state.brew.item);
	assert.equal(saved[0].dmg1, "1d8");
	assert.equal(saved[0].type, "M");
	await page.locator("[data-save]").click();
	await page.waitForFunction(() => document.querySelector("[data-status]").textContent.includes("Shared 1 records"));
	assert.equal(await page.evaluate(() => BrewUtil2._sharedClient.state.brew.item.length), 1);
	console.log("duplicate retry is idempotent PASS");
	await form.locator("[name=kind]").selectOption("subclass");
	await form.locator("[name=name]").fill("QA Moon Knight");
	await form.locator("[name=className]").fill("Fighter");
	await form.locator("[name=classSource]").fill("PHB");
	await page.locator("[data-add-feature]").click();
	await form.locator("[name=featureName]").fill("Moon Strike");
	await form.locator("[name=featureLevel]").fill("3");
	await form.locator("[name=featureDescription]").fill("Once on your turn, deal 1d6 radiant damage.");
	await page.getByRole("button", {name: "Check & preview", exact: true}).click();
	await page.waitForFunction(() => document.querySelector("[data-validation]").textContent.includes("Format and links checked."));
	await page.locator("[data-save]").click();
	await page.waitForFunction(() => document.querySelector("[data-status]").textContent.includes("Shared 2 records"));
	console.log("subclass and linked feature save PASS");
	await page.locator("#hb-books-tab").click();
	await page.locator("summary").filter({hasText: "Or paste text"}).click();
	const spell = "Starfire\n1st-level evocation\nCasting Time: 1 action\nRange: 60 feet\nComponents: V, S\nDuration: Instantaneous\nA creature takes 2d6 fire damage.";
	await page.locator("[data-paste]").fill(spell);
	await page.locator("[data-load-text]").click();
	await page.waitForSelector("[data-queue] button");
	console.log("queue", await page.locator("[data-counts]").innerText());
	await page.locator("[data-export]").click();
	await page.waitForFunction(() => document.querySelector("[data-book-status]").textContent.includes("remaining sections"));
	console.log("unreviewed export blocked PASS");
	await page.locator("[data-convert]").click();
	await page.waitForFunction(() => document.querySelector("[data-book-status]").textContent.includes("Conversion finished"), {timeout: 60000});
	console.log("parse report", await page.locator("[data-section-report]").innerText());
	const output = JSON.parse(await page.locator("[data-section-json]").inputValue());
	assert.equal(output.spell[0].name, "Starfire");
	await page.locator("[data-reviewed]").check();
	await page.locator("[data-approve]").click();
	await page.waitForFunction(() => document.querySelector("[data-book-status]").textContent.includes("Approved"));
	await page.locator("[data-import]").click();
	await page.waitForFunction(() => document.querySelector("[data-book-status]").textContent.includes("Shared 1 records"));
	console.log("parse-review-import spell PASS");
	const converterReports = await page.evaluate(async () => {
		const {convertSection, parseClassSection} = await import("/js/homebrew/book-converter.js");
		const {validateBrew} = await import("/js/homebrew/workshop-model.js");
		const {converterSample} = await (await fetch("/data/converter.json")).json();
		const source = {json: "QAConverters", full: "QA Converters", abbreviation: "QAC", version: "1.0.0", authors: []};
		const reports = [];
		for (const kind of ["race", "item", "feat", "background", "monster", "spell", "table"]) {
			const format = kind === "table" ? "md" : "txt";
			const sample = converterSample.find(it => it.converterId === kind && it.format === format && it.edition === "classic") || converterSample.find(it => it.converterId === kind && it.format === format);
			if (!sample) throw new Error(`No converter fixture for ${kind}`);
			const {brew} = await convertSection({kind, name: "Sample", page: 1, text: sample.text}, source, "classic");
			reports.push({kind, ...await validateBrew(brew)});
		}
		const cls = parseClassSection({kind: "class", name: "Moon Warden", page: 1, text: "Moon Warden\nHit Dice: 1d8 per level\nSaving Throws: Constitution, Wisdom\nA moon warrior.\nLevel 1: Moonlight\nYou shed dim light.\nLevel 3: Moon Strike\nDeal 1d6 radiant damage."}, source);
		reports.push({kind: "class", ...await validateBrew(cls.brew)});
		const alternate = await convertSection({kind: "background", name: "Test", page: 1, text: "Test Background\nSkill Proficiencies: Arcana, History\nLanguages: Common or one of your choice if you already speak Common\nEquipment: A book\nFeature: Research\nYou study books."}, source);
		reports.push({kind: "background-alternate-language", ...await validateBrew(alternate.brew)});
		return reports;
	});
	for (const report of converterReports) assert.deepEqual(report.errors, [], `${report.kind}: ${report.errors.join("; ")}`);
	console.log("All supported converter fixtures and class heading parser PASS");

	await page.locator("[data-section-text]").fill(`${spell}\nIt also glows.`);
	assert.equal(await page.locator("[data-reviewed]").isChecked(), false);
	assert.equal(await page.locator("[data-section-json]").inputValue(), "");
	console.log("edit invalidates approval PASS");
	const print = await browser.newPage();
	await print.setContent("<html><body style=\"font-family:Arial; font-size:12px\"><h1>Starfire</h1><p>1st-level evocation</p><p>Casting Time: 1 action</p><p>Range: 60 feet</p><p>Components: V, S</p><p>Duration: Instantaneous</p><p>A creature takes 2d6 fire damage.</p><div style=\"break-before:page\"><h1>Book Notes</h1><p>This is ordinary prose kept for review.</p></div></body></html>");
	await print.pdf({path: path.join(temp, "sample.pdf"), format: "A4"});
	page.on("dialog", d => d.accept());
	await page.locator("[data-file]").setInputFiles(path.join(temp, "sample.pdf"));
	await page.locator("[data-load]").click();
	await page.waitForFunction(() => document.querySelector("[data-book-status]").textContent.includes("Loaded 2 pages"), {timeout: 60000});
	console.log("PDF extraction PASS", await page.locator("[data-counts]").innerText());
	await page.locator("[data-pages-panel] > summary").click();
	await page.locator("[data-show-page]").click();
	await page.waitForFunction(() => !document.querySelector("[data-canvas]").hidden && document.querySelector("[data-canvas]").width > 0);
	console.log("PDF rendering PASS");
	await page.locator("[data-parse-all]").click();
	await page.waitForFunction(() => document.querySelector("[data-book-status]").textContent.includes("Batch conversion"));
	await page.locator("[data-reviewed]").check();
	await page.locator("[data-approve]").click();
	await page.waitForFunction(() => document.querySelector("[data-book-status]").textContent.includes("Approved"));
	await page.locator("[data-queue] button").nth(1).click();
	await page.locator("[data-exclude]").click();
	await page.locator("[data-export]").click();
	assert.match(await page.locator("[data-book-status]").innerText(), /page-review checkbox/);
	await page.locator("[data-pages-reviewed]").check();
	await page.locator("[data-include-book]").check();
	const downloadWait = page.waitForEvent("download");
	await page.locator("[data-export]").click();
	const download = await downloadWait;
	const file = path.join(temp, "homebrew.json");
	await download.saveAs(file);
	const exported = JSON.parse(await readFile(file, "utf8"));
	assert.equal(exported.spell.length, 1);
	assert.equal(exported.bookData[0].data.length, 2);
	console.log("Reviewed PDF plus readable book export PASS");
	await page.locator("[data-import]").click();
	await page.waitForFunction(() => document.querySelector("[data-book-status]").textContent.includes("Shared 3 records"));
	const reader = await page.context().newPage();
	reader.on("pageerror", error => errors.push(error.message));
	await reader.goto(`${baseUrl}/book.html#${exported.book[0].id.toLowerCase()}`);
	await reader.waitForFunction(() => document.body.textContent.includes("2d6 fire damage"), null, {timeout: 60000});
	await reader.close();
	console.log("Imported book reader PASS");
	const projectWait = page.waitForEvent("download");
	await page.locator("[data-project]").click();
	const projectDownload = await projectWait;
	const projectFile = path.join(temp, "review.json");
	await projectDownload.saveAs(projectFile);
	await page.waitForFunction(() => document.querySelector("[data-storage-status]").textContent.includes("Review saved"));
	await page.reload();
	await page.waitForSelector(".hb-workshop");
	await page.locator("#hb-books-tab").click();
	await page.locator("[data-restore]").click();
	await page.waitForFunction(() => document.querySelector("[data-book-status]").textContent.includes("Last review restored"));
	assert.match(await page.locator("[data-counts]").innerText(), /1 approved.*1 excluded/);
	console.log("Autosave restore PASS");
	await page.locator("[data-file]").setInputFiles(projectFile);
	await page.locator("[data-load]").click();
	await page.waitForFunction(() => document.querySelector("[data-book-status]").textContent.includes("Review project loaded"));
	assert.match(await page.locator("[data-counts]").innerText(), /1 approved.*1 excluded/);
	console.log("Review download and restore PASS");
	await page.setViewportSize({width: 390, height: 844});
	assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 2));
	console.log("Mobile layout PASS");

	console.log("pageerrors", JSON.stringify(errors));
	assert.deepEqual(errors, []);
} finally { await browser.close(); if (server.exitCode == null && server.signalCode == null) { const exited = new Promise(resolve => server.once("exit", resolve)); server.kill("SIGTERM"); await exited; } await rm(temp, {recursive: true, force: true}); }
